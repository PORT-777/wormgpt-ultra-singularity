def _convert_one(rule: Dict[str, Any], selections: Dict[str, Any],
                 condition: str, logsource: Dict[str, Any], target: str) -> str:
    if target == "splunk":
        return _to_splunk(rule, selections, condition, logsource)
    if target == "kql":
        return _to_kql(rule, selections, condition, logsource)
    if target == "eql":
        return _to_eql(rule, selections, condition, logsource)
    if target == "aql":
        return _to_aql(rule, selections, condition)
    if target == "yara-l":
        return _to_yaral(rule, selections, condition)
    raise ValueError(f"unsupported target {target}")


def _sel_conditions(sel: Dict[str, Any], flavor: str, fields: Dict[str, str]) -> List[str]:
    out = []
    for field, values in sel.items():
        if not isinstance(values, list):
            values = [values]
        base, *mods = str(field).split("|")
        f = fields.get(base, base)
        for value in values:
            op, v = _modifier_to_op(str(value), mods, flavor)
            if flavor == "splunk":
                out.append(f'{f}{op}"{v}"' if op in ("=", "!=") else f'{f}{op}"{v}"')
            elif flavor == "kql":
                out.append(f'{f} {op} "{v}"')
            elif flavor == "eql":
                out.append(f'{f} {op} "{v}"')
            elif flavor == "aql":
                if op in (":", "="):
                    out.append(f'LOWER("{f}") LIKE \'%{v.lower()}%\'')
                else:
                    out.append(f'LOWER("{f}") LIKE \'%{v.lower()}%\'')
    return out


def _modifier_to_op(value: str, mods: List[str], flavor: str) -> Tuple[str, str]:
    mods = [m.lower() for m in mods]
    if "endswith" in mods:
        return ("=", f"*{value}") if flavor == "splunk" else (":", f"*{value}")
    if "startswith" in mods:
        return ("=", f"{value}*") if flavor == "splunk" else (":", f"{value}*")
    if "contains" in mods or "windash" in mods:
        return ("=", f"*{value}*") if flavor == "splunk" else (":", f"*{value}*")
    if "re" in mods:
        return ("=", f"{value}") if flavor == "splunk" else (":", f"/{value}/")
    if "gt" in mods:
        return (">", value)
    if "lt" in mods:
        return ("<", value)
    if flavor == "splunk":
        return ("=", value)
    return ("==", value)


def _to_splunk(rule: Dict[str, Any], selections: Dict[str, Any],
               condition: str, logsource: Dict[str, Any]) -> str:
    index = logsource.get("index", "windows")
    category = logsource.get("category", "")
    product = logsource.get("product", "")
    sourcetype = ""
    if category == "process_creation":
        sourcetype = "WinEventLog:Security" if product == "windows" else ""
    elif category == "dns_query":
        sourcetype = "dns"
    elif category == "network_connection":
        sourcetype = "network"
    prefix = f"index={index}"
    if sourcetype:
        prefix += f' sourcetype="{sourcetype}"'
    blocks = []
    for name, sel in selections.items():
        if isinstance(sel, list):
            sel = {"CommandLine|contains": sel}
        if not isinstance(sel, dict):
            continue
        conds = _sel_conditions(sel, "splunk", {})
        if conds:
            blocks.append((name, "(" + " OR ".join(conds) + ")"))
    cond = condition
    for name, block in blocks:
        cond = cond.replace(name, block)
    cond = cond.replace("1 of them", " OR ".join(b[1] for b in blocks) or "*")
    cond = cond.replace("all of them", " ".join(b[1] for b in blocks) or "*")
    if "selection" in cond and blocks:
        cond = cond.replace("selection", blocks[0][1])
    if " of " in cond:
        cond = " OR ".join(b[1] for b in blocks) or "*"
    return f"{prefix} {cond} | stats count by host, user, Image, CommandLine"


