def query_translate(query: str, source: str = "", target: str = "kql") -> Dict[str, Any]:
    src = (source or _detect_query_lang(query)).lower()
    tgt = target.lower()
    fields = _extract_query_fields(query, src)
    where = " and ".join(f'{k} = "{v}"' for k, v in fields.items()) or "true"
    if tgt == "splunk":
        spl = " ".join(f'{k}="{v}"' for k, v in fields.items())
        out = f"index=windows {spl or '*'}" + " | stats count by host, user"
    elif tgt == "kql":
        out = f"DeviceProcessEvents\n| where {where}\n| project Timestamp, DeviceName, AccountName, FileName, ProcessCommandLine"
    elif tgt == "eql":
        out = f"process where {where}"
    elif tgt == "aql":
        conds = " AND ".join(f'LOWER("{k}") LIKE \'%{v.lower()}%\'' for k, v in fields.items()) or "1=1"
        out = f"SELECT * FROM events WHERE {conds}"
    elif tgt == "yara-l":
        ev = "\n    ".join(f'$e.{k} = "{v}"' for k, v in fields.items()) or '$e.metadata.event_type = "PROCESS_LAUNCH"'
        out = f"rule translated {{\n  events:\n    {ev}\n  condition:\n    $e\n}}"
    else:
        raise ValueError(f"unsupported target {target}")
    return {"source_language": src, "target": tgt, "translated": out,
            "fields": fields,
            "warnings": ["Field mappings approximate; validate against your schema."]}


def _detect_query_lang(q: str) -> str:
    low = q.lower()
    if "| where" in low or "deviceprocessevents" in low or "securityevent" in low:
        return "kql"
    if low.startswith("select ") or " from events" in low:
        return "aql"
    if "process where" in low and ":" in q:
        return "eql"
    if "index=" in low or "stats " in low or "| search" in low:
        return "splunk"
    if "rule " in low and "events:" in low:
        return "yara-l"
    return "splunk"


def _extract_query_fields(q: str, lang: str) -> Dict[str, str]:
    out: Dict[str, str] = {}
    patterns = [
        r'(\w+)\s*=\s*"([^"]+)"', r'(\w+)\s*==\s*"([^"]+)"',
        r'(\w+)\s*:\s*"([^"]+)"', r'"(\w+)"\s*=\s*\'([^\']+)\'',
    ]
    for pat in patterns:
        for m in re.finditer(pat, q):
            key, val = m.group(1), m.group(2)
            val = val.strip("*")
            if key.lower() in ("index", "timestamp", "ago", "table"):
                continue
            out[_canonical_field(key)] = val
    if not out:
        for m in re.finditer(r"\b([A-Za-z_][\w.]*)\s+has\s+\"([^\"]+)\"", q):
            out[_canonical_field(m.group(1))] = m.group(2)
    return out


def _canonical_field(field: str) -> str:
    mapping = {"image": "Image", "processname": "Image", "filename": "Image",
               "commandline": "CommandLine", "processcommandline": "CommandLine",
               "parentimage": "ParentImage", "eventid": "EventID",
               "eventcode": "EventID", "user": "User", "accountname": "User",
               "dest_ip": "DestinationIp", "remoteip": "DestinationIp",
               "queryname": "QueryName", "name": "QueryName"}
    return mapping.get(field.lower().replace("_", ""), field)


