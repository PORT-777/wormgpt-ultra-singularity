_KEYWORD_INDEX: List[Tuple[str, Dict[str, Any], str]] = []
for _t in TECHNIQUES:
    for _kw in _t.get("keywords", []):
        _KEYWORD_INDEX.append((_kw.lower(), _t, _kw))
_KEYWORD_INDEX.sort(key=lambda x: len(x[0]), reverse=True)


def mitre_map(text: str, extra: Optional[Sequence[str]] = None,
              min_confidence: int = 30) -> Dict[str, Any]:
    low = (text or "").lower()
    extra_low = " ".join(extra or []).lower()
    hits: Dict[str, Dict[str, Any]] = {}
    for keyword, tech, original in _KEYWORD_INDEX:
        if keyword and keyword in low:
            item = hits.setdefault(tech["id"], {
                "id": tech["id"], "name": tech["name"], "tactic": tech["tactic"],
                "description": tech.get("description", ""),
                "evidence": [], "keywords": [], "detection": tech.get("detection", []),
            })
            item["keywords"].append(original)
            item["evidence"].append(_evidence_line(text, original))
    # explicit technique IDs in text
    for m in re.finditer(r"\bT\d{4}(?:\.\d{3})?\b", text or "", re.I):
        tid = m.group().upper()
        tech = TECHNIQUE_INDEX.get(tid)
        if tech and tid not in hits:
            hits[tid] = {"id": tid, "name": tech["name"], "tactic": tech["tactic"],
                         "evidence": [f"explicit mention {tid}"],
                         "keywords": [tid], "detection": tech.get("detection", [])}
    out = []
    for item in hits.values():
        count = len(item["keywords"])
        confidence = min(96, 35 + count * 12 + (10 if item["tactic"] in ("Credential Access", "Command and Control", "Impact") else 0))
        if confidence >= min_confidence:
            out.append({**item, "confidence": confidence,
                        "mitre_url": f"https://attack.mitre.org/techniques/{item['id'].replace('.', '/')}/"})
    out.sort(key=lambda x: (-x["confidence"], TACTIC_ORDER.index(x["tactic"])
                            if x["tactic"] in TACTIC_ORDER else 99))
    tactics: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for item in out:
        tactics[item["tactic"]].append({"id": item["id"], "name": item["name"],
                                        "confidence": item["confidence"]})
    return {"techniques": out, "count": len(out), "by_tactic": dict(tactics),
            "tactics_observed": list(tactics.keys())}


def _evidence_line(text: str, keyword: str, width: int = 80) -> str:
    idx = text.lower().find(keyword.lower())
    if idx < 0:
        return f"matched {keyword!r}"
    start = max(0, idx - width // 2)
    end = min(len(text), idx + len(keyword) + width // 2)
    return text[start:end].replace("\n", " ").strip()


def mitre_navigator(mapped: Dict[str, Any], name: str = "CyberOps coverage") -> Dict[str, Any]:
    techniques = []
    for item in mapped.get("techniques", []):
        tid = item["id"]
        parts = tid.split(".")
        if len(parts) == 2:
            score = item["confidence"] / 100
        else:
            score = item["confidence"] / 100
        techniques.append({"techniqueID": tid, "score": round(score, 2),
                           "color": _score_color(score),
                           "comment": ", ".join(item.get("keywords", [])[:5])})
    return {
        "name": name, "versions": {"attack": "15", "navigator": "4.9.1",
                                   "layer": "4.5"},
        "domain": "enterprise-attack", "description": "Generated by CyberOps",
        "techniques": techniques,
        "gradient": {"colors": ["#ffffff", "#ffd700", "#ff8c00", "#ff0000"],
                     "minValue": 0, "maxValue": 1},
        "legendItems": [{"label": "Low confidence", "color": "#ffd700"},
                        {"label": "High confidence", "color": "#ff0000"}],
    }


def _score_color(score: float) -> str:
    if score >= 0.75:
        return "#ff0000"
    if score >= 0.5:
        return "#ff8c00"
    return "#ffd700"


def coverage_score(techniques: Sequence[Any], detections: Sequence[str] = ()) -> Dict[str, Any]:
    ids = []
    for t in techniques:
        if isinstance(t, dict):
            ids.append(t.get("id", ""))
        else:
            ids.extend(re.findall(r"T\d{4}(?:\.\d{3})?", str(t).upper()))
    if not ids and detections:
        ids = [t["id"] for t in mitre_map(" ".join(detections))["techniques"]]
    ids = [i for i in dict.fromkeys(ids) if i]
    covered_by_tactic: Dict[str, List[str]] = defaultdict(list)
    for tid in ids:
        tech = TECHNIQUE_INDEX.get(tid)
        if tech:
            covered_by_tactic[tech["tactic"]].append(tid)
    heatmap = []
    for tactic in TACTIC_ORDER:
        total = len([t for t in TECHNIQUES if t["tactic"] == tactic])
        covered = len(covered_by_tactic.get(tactic, []))
        pct = round(covered / total * 100, 1) if total else 0.0
        heatmap.append({"tactic": tactic, "covered": covered, "total": total,
                        "percent": pct, "techniques": covered_by_tactic.get(tactic, []),
                        "quality": "alerting" if pct >= 60 else
                                   ("hunting" if pct >= 25 else "blind")})
    overall = round(sum(h["percent"] for h in heatmap) / len(heatmap), 1)
    return {"overall_percent": overall, "heatmap": heatmap,
            "covered_techniques": ids,
            "gaps": [h["tactic"] for h in heatmap if h["quality"] == "blind"],
            "verdict": "strong" if overall >= 60 else ("moderate" if overall >= 30 else "weak")}


def defense_gap_analysis(tools: Sequence[str]) -> Dict[str, Any]:
    tool_map = {
        "edr": ["Execution", "Persistence", "Privilege Escalation", "Defense Evasion",
                "Credential Access", "Discovery", "Lateral Movement"],
        "siem": ["Initial Access", "Execution", "Persistence", "Credential Access",
                 "Lateral Movement", "Command and Control", "Exfiltration", "Impact"],
        "ndr": ["Command and Control", "Exfiltration", "Lateral Movement", "Discovery"],
        "waf": ["Initial Access"],
        "email gateway": ["Initial Access"],
        "dlp": ["Exfiltration", "Collection"],
        "ueba": ["Credential Access", "Discovery", "Lateral Movement"],
        "deception": ["Discovery", "Lateral Movement", "Credential Access"],
        "vulnerability scanner": ["Initial Access", "Privilege Escalation"],
        "backup": ["Impact"],
        "immutable backup": ["Impact"],
        "mfa": ["Initial Access", "Credential Access"],
        "pam": ["Credential Access", "Lateral Movement"],
        "ndr/ids": ["Command and Control", "Exfiltration"],
        "soar": ["Impact", "Exfiltration"],
        "xdr": ["Execution", "Persistence", "Defense Evasion", "Credential Access",
                "Lateral Movement", "Command and Control"],
    }
    covered = set()
    used = []
    for tool in tools:
        low = tool.lower()
        for key, tactics in tool_map.items():
            if key in low:
                covered.update(tactics)
                used.append({"tool": tool, "tactics": tactics})
                break
    gaps = [t for t in TACTIC_ORDER if t not in covered]
    return {"tools_recognized": used, "covered_tactics": sorted(covered, key=TACTIC_ORDER.index),
            "gaps": gaps, "coverage_percent": round(len(covered) / len(TACTIC_ORDER) * 100, 1),
            "priority": gaps[:5]}


