def sigma_validate(rule_text: str) -> Dict[str, Any]:
    issues = []
    try:
        rule = yaml.safe_load(rule_text) if yaml is not None else json.loads(rule_text)
    except Exception as exc:
        return {"valid": False, "issues": [f"YAML parse error: {exc}"], "score": 0}
    if not isinstance(rule, dict):
        return {"valid": False, "issues": ["rule is not a mapping"], "score": 0}
    required = ["title", "logsource", "detection"]
    for key in required:
        if key not in rule:
            issues.append(f"missing required field: {key}")
    det = rule.get("detection", {})
    if not isinstance(det, dict):
        issues.append("detection must be a mapping")
    else:
        if "condition" not in det:
            issues.append("missing detection.condition")
        if not any(k != "condition" for k in det):
            issues.append("no selections in detection block")
        cond = str(det.get("condition", ""))
        names = [k for k in det if k != "condition"]
        for name in names:
            if name not in cond and " of " not in cond:
                issues.append(f"selection '{name}' is not referenced by condition")
        for name, sel in det.items():
            if name == "condition":
                continue
            if isinstance(sel, dict):
                for field in sel:
                    if "|" in field:
                        mod = field.split("|", 1)[1].split("|")[0]
                        if mod not in ("contains", "startswith", "endswith", "re", "all",
                                       "base64", "base64offset", "cidr", "gt", "lt", "gte",
                                       "lte", "windash", "utf16", "utf16le", "utf16be",
                                       "wide", "nocase", "fieldref"):
                            issues.append(f"unknown modifier '{mod}' in {field}")
    if not rule.get("falsepositives") and not rule.get("falsepositives") == []:
        issues.append("missing falsepositives (recommended)")
    if not rule.get("level"):
        issues.append("missing level (recommended)")
    if not rule.get("tags"):
        issues.append("missing ATT&CK tags (recommended)")
    score = max(0, 100 - len(issues) * 10)
    return {"valid": not [i for i in issues if i.startswith(("missing required", "detection must", "no selections", "missing detection", "selection '"))],
            "issues": issues, "score": score, "rule_title": rule.get("title", "")}


def sigma_test(rule_text: str, samples: Sequence[Any]) -> Dict[str, Any]:
    try:
        rule = yaml.safe_load(rule_text) if yaml is not None else json.loads(rule_text)
    except Exception as exc:
        return {"error": str(exc), "results": []}
    det = rule.get("detection", {}) if isinstance(rule, dict) else {}
    selections = {k: v for k, v in det.items() if k != "condition"}
    condition = str(det.get("condition", "selection"))
    results = []
    for sample in samples:
        text = json.dumps(sample) if not isinstance(sample, str) else sample
        matched_sel = {}
        for name, sel in selections.items():
            if isinstance(sel, list):
                sel = {"CommandLine|contains": sel}
            if not isinstance(sel, dict):
                continue
            conds = []
            for field, values in sel.items():
                if not isinstance(values, list):
                    values = [values]
                base, *mods = str(field).split("|")
                val = _get_field(sample, base, text)
                for v in values:
                    conds.append(_match_value(val, str(v), mods))
            matched_sel[name] = all(conds) if conds else False
        ok = _eval_condition(condition, matched_sel)
        results.append({"sample": text[:200], "matched": ok,
                        "selections": matched_sel})
    return {"rule_title": rule.get("title", ""), "results": results,
            "matched_count": sum(1 for r in results if r["matched"]),
            "tested": len(results)}


def _get_field(sample: Any, field: str, text: str) -> str:
    if isinstance(sample, dict):
        for key in (field, field.lower(), field.replace("_", "")):
            if key in sample:
                return str(sample[key])
        for key, value in sample.items():
            if key.lower() == field.lower():
                return str(value)
    return text


def _match_value(actual: str, expected: str, mods: Sequence[str]) -> bool:
    low_mods = [m.lower() for m in mods]
    a, e = actual, expected
    if "re" in low_mods:
        try:
            return bool(re.search(e, a))
        except re.error:
            return False
    if "nocase" in low_mods:
        a, e = a.lower(), e.lower()
    if "contains" in low_mods:
        return e in a
    if "startswith" in low_mods:
        return a.startswith(e)
    if "endswith" in low_mods:
        return a.endswith(e)
    if "gt" in low_mods:
        try:
            return float(a) > float(e)
        except ValueError:
            return False
    if "lt" in low_mods:
        try:
            return float(a) < float(e)
        except ValueError:
            return False
    return a == e


def _eval_condition(condition: str, matched: Dict[str, bool]) -> bool:
    cond = condition.strip()
    for name, val in matched.items():
        cond = cond.replace(name, "True" if val else "False")
    if "1 of " in cond:
        return any(matched.values())
    if "all of " in cond:
        return all(matched.values())
    m = re.search(r"(\d+) of ", cond)
    if m:
        return sum(1 for v in matched.values() if v) >= int(m.group(1))
    try:
        return bool(eval(cond, {"__builtins__": {}}, {}))
    except Exception:
        return any(matched.values())


