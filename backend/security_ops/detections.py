_GENERIC_STRINGS = {
    "this program", "microsoft", "copyright", "all rights reserved", "http",
    "https", "software", "windows", "system32", "kernel32.dll", "user32.dll",
    "advapi32.dll", "msvcrt.dll", "shell32.dll", ".text", ".data", ".rdata",
    "getprocaddress", "loadlibrarya", "exitprocess", "virtualalloc",
}

_BAD_RULE_CHARS = re.compile(r"[^A-Za-z0-9_]")


def _yara_escape(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return out


def _candidate_strings(text: str, data: bytes, limit: int = 12) -> List[Dict[str, Any]]:
    candidates: Dict[str, Dict[str, Any]] = {}
    parsed = extract_strings(data, 6, True, True, 12000) if data else {"ascii": [], "unicode": []}
    pool: List[Tuple[str, bool]] = [(s, False) for s in parsed.get("ascii", [])]
    pool += [(s, True) for s in parsed.get("unicode", [])]
    # Text input: keep full printable chunks but also split tokens so a rule
    # generated from a paragraph still matches an individual indicator.
    for line in (text or "").splitlines():
        pool.extend((chunk.strip(), False)
                    for chunk in re.findall(r"[ -~]{6,200}", line))
        for token in re.split(r"\s+", line):
            token = token.strip(" \t\r\n,;:\"'`()[]{}<>")
            if len(token) >= 6:
                pool.append((token, False))
    for raw, wide in pool:
        s = raw.strip()
        if len(s) < 6 or len(s) > 160:
            continue
        if s.lower() in _GENERIC_STRINGS:
            continue
        if re.fullmatch(r"[\d\W_]+", s):
            continue
        if len(set(s)) <= 3:
            continue
        score = len(s) + entropy(s.encode()) * 6
        if any(k in s for k in ("http://", "https://", "\\\\", "HKEY_", "cmd.exe",
                                "powershell", "CurrentVersion\\Run", ".onion")):
            score += 20
        candidates[s] = {"value": s, "score": round(score, 1),
                         "wide": bool(wide and len(s) > 4),
                         "case": bool(re.search(r"[A-Z]", s))}
    ranked = sorted(candidates.values(), key=lambda x: x["score"], reverse=True)
    return ranked[:limit]


def yara_generate(text: str = "", data: bytes = b"", name: str = "",
                  description: str = "", author: str = "CyberOps",
                  max_strings: int = 12, is_pe: bool = False,
                  include_hashes: bool = True) -> Dict[str, Any]:
    rule_name = _BAD_RULE_CHARS.sub("_", name or "CyberOps_Generated")
    if not rule_name or not rule_name[0].isalpha():
        rule_name = "R_" + rule_name
    candidates = _candidate_strings(text, data, max_strings)
    if not candidates:
        # fall back to unique byte sequences
        candidates = _byte_candidates(data, max_strings)
    strings_block = []
    used = set()
    for i, c in enumerate(candidates, 1):
        if c["value"] in used:
            continue
        used.add(c["value"])
        if c.get("hex"):
            strings_block.append(f"        $s{i} = {{ {c['value']} }}")
        else:
            modifiers = "ascii wide" if c.get("wide") else "ascii"
            strings_block.append(f'        $s{i} = "{_yara_escape(c["value"])}" {modifiers}')
    meta = [f'        author = "{_yara_escape(author)}"',
            f'        date = "{datetime.now(timezone.utc).strftime("%Y-%m-%d")}"',
            f'        description = "{_yara_escape(description or "Generated from observed artifacts")}"',
            '        reference = "CyberOps local analysis"']
    if data:
        meta.append(f'        sample_sha256 = "{hashlib.sha256(data).hexdigest()}"')
        meta.append(f'        sample_size = {len(data)}')
    cond_parts = []
    if is_pe or (data[:2] == b"MZ"):
        cond_parts.append("uint16(0) == 0x5A4D")
    if data:
        cond_parts.append(f"filesize < {max(1, math.ceil(len(data) * 4 / 1048576))}MB")
    cond_parts.append("any of them")
    condition = " and ".join(cond_parts)
    strings_blob = chr(10).join(strings_block) if strings_block else \
        '        $s1 = "CyberOpsNoStrings" ascii'
    rule = f"""rule {rule_name}
{{
    meta:
{chr(10).join(meta)}
    strings:
{strings_blob}
    condition:
        {condition}
}}"""
    return {"rule_name": rule_name, "rule": rule,
            "string_count": len(strings_block), "strings": candidates,
            "condition": condition,
            "notes": ["Unique strings preferred over generic API names.",
                      "Review and add a hash or PE condition for production use.",
                      "Test against a benign corpus before deployment."]}


def _byte_candidates(data: bytes, limit: int) -> List[Dict[str, Any]]:
    out = []
    seen = set()
    for i in range(0, max(0, len(data) - 12), 4):
        chunk = data[i:i + 12]
        if len(set(chunk)) < 5 or chunk in seen:
            continue
        seen.add(chunk)
        out.append({"value": chunk.hex().upper(), "hex": True,
                    "score": round(entropy(chunk) * 4 + 12, 1)})
        if len(out) >= limit * 3:
            break
    out.sort(key=lambda x: x["score"], reverse=True)
    return out[:limit]


def yara_scan(rule_text: str, data: bytes, filename: str = "") -> Dict[str, Any]:
    try:
        import yara  # type: ignore
        rules = yara.compile(source=rule_text)
        matches = rules.match(data=data)
        out = []
        for m in matches:
            out.append({"rule": m.rule, "tags": list(m.tags), "namespace": m.namespace,
                        "meta": m.meta,
                        "strings": [{"identifier": s.identifier, "offset": s.offset,
                                     "data": bytes(s.data).hex()[:64]}
                                    for s in m.strings]})
        return {"engine": "yara-python", "matches": out, "filename": filename}
    except ImportError:
        return _yara_scan_builtin(rule_text, data, filename)
    except Exception as exc:
        return {"engine": "yara-python", "error": str(exc),
                "matches": [], "filename": filename}


def _parse_simple_rules(rule_text: str) -> List[Dict[str, Any]]:
    rules = []
    for m in re.finditer(r"rule\s+([A-Za-z0-9_]+)\s*\{(.*?)\n\}", rule_text, re.S):
        name, body = m.group(1), m.group(2)
        strings = []
        for sm in re.finditer(r'(\$[A-Za-z0-9_]+)\s*=\s*"((?:\\.|[^"])*)"\s*([a-z ]*)', body):
            val = sm.group(2).replace('\\"', '"').replace("\\\\", "\\")
            strings.append({"id": sm.group(1), "value": val,
                            "wide": "wide" in sm.group(3),
                            "nocase": "nocase" in sm.group(3)})
        for sm in re.finditer(r"(\$[A-Za-z0-9_]+)\s*=\s*\{\s*([0-9A-Fa-f ?]+)\s*\}", body):
            raw = re.sub(r"[^0-9A-Fa-f]", "", sm.group(2))
            if len(raw) % 2:
                raw = raw[:-1]
            strings.append({"id": sm.group(1), "value": bytes.fromhex(raw),
                            "hex": True, "wide": False, "nocase": False})
        cm = re.search(r"condition\s*:\s*(.+)", body, re.S)
        condition = cm.group(1).strip() if cm else "any of them"
        rules.append({"name": name, "strings": strings, "condition": condition})
    return rules


def _yara_scan_builtin(rule_text: str, data: bytes, filename: str) -> Dict[str, Any]:
    rules = _parse_simple_rules(rule_text)
    matches = []
    for rule in rules:
        hit = []
        for s in rule["strings"]:
            value = s["value"]
            if s.get("hex"):
                idx = data.find(value)
                if idx >= 0:
                    hit.append({"identifier": s["id"], "offset": idx, "data": value.hex()})
                continue
            needles = [value.encode("utf-8", "replace")]
            if s.get("wide"):
                needles.append(value.encode("utf-16le", "replace"))
            for needle in needles:
                hay = data.lower() if s.get("nocase") else data
                nd = needle.lower() if s.get("nocase") else needle
                idx = hay.find(nd)
                if idx >= 0:
                    hit.append({"identifier": s["id"], "offset": idx,
                                "data": needle[:48].hex()})
                    break
        if _eval_yara_condition(rule["condition"], hit, data):
            matches.append({"rule": rule["name"], "strings": hit, "tags": [],
                            "meta": {"engine": "builtin"}})
    return {"engine": "builtin", "matches": matches, "filename": filename,
            "note": "install yara-python for full YARA semantics"}


def _eval_yara_condition(condition: str, hits: List[Dict[str, Any]], data: bytes) -> bool:
    cond = condition.strip().rstrip(";")
    n = len(hits)
    # Replace common idioms
    cond = re.sub(r"any\s+of\s+them", "True" if n >= 1 else "False", cond)
    cond = re.sub(r"all\s+of\s+them", "True" if n >= max(1, 1) and n >= 1 else "False", cond)
    m = re.search(r"(\d+)\s+of\s+them", cond)
    if m:
        cond = cond.replace(m.group(0), "True" if n >= int(m.group(1)) else "False")
    cond = re.sub(r"uint16\(0\)\s*==\s*0x5A4D", "True" if data[:2] == b"MZ" else "False", cond, flags=re.I)
    m = re.search(r"filesize\s*<\s*(\d+)\s*(KB|MB|GB)?", cond, re.I)
    if m:
        size = int(m.group(1))
        unit = (m.group(2) or "").upper()
        mult = {"KB": 1024, "MB": 1024 ** 2, "GB": 1024 ** 3}.get(unit, 1)
        cond = cond.replace(m.group(0), "True" if len(data) < size * mult else "False")
    cond = re.sub(r"\btrue\b", "True", cond, flags=re.I)
    cond = re.sub(r"\bfalse\b", "False", cond, flags=re.I)
    for i, h in enumerate(hits):
        cond = cond.replace(f'${h["identifier"]}', "True")
    cond = re.sub(r"\$[A-Za-z0-9_]+", "False", cond)
    cond = cond.replace(" and ", " and ").replace(" or ", " or ").replace("not ", " not ")
    if re.fullmatch(r"[TrueFalsenadort ()0-9<>=!]+", cond.replace("True", "T").replace("False", "F")):
        try:
            return bool(eval(cond, {"__builtins__": {}}, {}))
        except Exception:
            return n > 0
    return n > 0


